/* ЭЛТ-кинескоп: модель настоящего телевизора/монитора для кадра игры.
 *
 * Кадр игры — это и есть сигнал, как у приставки на телевизоре: каждая строка
 * игры рисуется строкой развёртки. Модель подобрана по снимку настоящего ЭЛТ
 * (те же формулы, что у шейдера CRT Tube из crt-overlay):
 *   - яркость идёт узким гауссовым лучом по строке, цвет — широким
 *     (у композитного сигнала цвету отведена узкая полоса — он растекается вбок);
 *   - строка — гауссова по высоте, на светлом толще, на тёмном тоньше;
 *   - апертурная решётка: полосы R, G, B;
 *   - сведение: красный и синий лучи чуть разъехались;
 *   - гамма, яркость, насыщенность.
 * Считается на процессоре, без OpenGL; тяжёлые функции — таблицами. */
#ifndef BT_CRT_H
#define BT_CRT_H

#include <stdint.h>

/* Настройки по порядку — так они идут в меню и в pc.cfg. */
enum {
    CRT_SCAN_DARK,   /* толщина строки на тёмном, доля строки */
    CRT_SCAN_BRIGHT, /* толщина строки на светлом */
    CRT_SHARP,       /* ширина луча яркости, пикселей игры */
    CRT_SMEAR,       /* растекание цвета, пикселей игры */
    CRT_COLOR,       /* цветность сигнала (ручка «Цвет» у телевизора) */
    CRT_SAT,         /* насыщенность на экране */
    CRT_BRIGHT,      /* яркость */
    CRT_CONTRAST,    /* контраст: гамма сигнала */
    CRT_MASK,        /* сила апертурной решётки */
    CRT_MASK_PITCH,  /* шаг решётки, в строках */
    CRT_CONV_R,      /* сведение красного, пикселей игры */
    CRT_CONV_B,      /* сведение синего */
    CRT_GAIN_R,      /* баланс белого: красный */
    CRT_GAIN_B,      /* баланс белого: синий */
    CRT_NPARAM
};

typedef struct {
    const char *key;     /* имя в pc.cfg */
    const char *label;   /* подпись в меню */
    float def, min, max, step;
} CrtParamInfo;

extern const CrtParamInfo crt_param_info[CRT_NPARAM];

typedef struct {
    float v[CRT_NPARAM];
} CrtParams;

void crt_defaults(CrtParams *p);

/* Рисует кадр игры src (sw×sh, ARGB) кинескопом в dst размером
 * (sw·kx)×(sh·ky): ky — экранных строк на строку игры, kx — пикселей на пиксель.
 * threads — сколько ядер процессора занять (строки делятся между ними).
 * Таблицы пересчитываются сами, когда меняются размеры или настройки.
 * 0 — готово, -1 — не хватило памяти. */
int crt_render(const uint32_t *src, int sw, int sh, uint32_t *dst, int kx, int ky, const CrtParams *p, int threads);

/* Освободить таблицы и буферы. */
void crt_free(void);

#endif
